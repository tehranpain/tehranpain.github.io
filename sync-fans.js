const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const { setTimeout: sleep } = require('node:timers/promises');

const DATA_FILE = path.join(__dirname, 'data/artist-data.js');
const CACHE_FILE = path.join(__dirname, 'fans-cache.js');
const ACCESS_CODES = new Set([301, 302, 303, 307, 308, 401, 403, 405, 429, -462]);
const PROBE_IDS = ['865007', '1132392', '12198387', '31561897', '12563131'];
const PUBLISH_COVERAGE = 0.95;

class AccessError extends Error {}

function formatFans(count) {
  if (!Number.isFinite(count) || count < 0) return '';
  return count >= 10000 ? (count / 10000).toFixed(1).replace(/\.0$/, '') + '万' : String(count);
}

function readWindow(file) {
  const context = { window: {} };
  vm.runInNewContext(fs.readFileSync(file, 'utf8'), context, { timeout: 3000, filename: file });
  return context.window;
}

function extractArtists(data) {
  const artists = new Map();
  for (const person of [...data.singers || [], ...data.profiles || []]) {
    const id = String(person.neteaseId || '');
    if (person.profileDisabled || !/^\d+$/.test(id) || +id <= 0) continue;
    const names = [person.name, ...person.aliases || []].filter(name => typeof name === 'string' && name.trim());
    const previous = artists.get(id);
    if (previous) previous.names = [...new Set([...previous.names, ...names])];
    else artists.set(id, { id, name: person.name, names: [...new Set(names)], fans: person.fans || '' });
  }
  return [...artists.values()];
}

function exactFans(result, id) {
  const artist = (result.result?.artists || []).find(item => String(item.id) === String(id));
  return Number.isSafeInteger(artist?.fansSize) && artist.fansSize >= 0 ? artist.fansSize : null;
}

function createClient({ delayMs = 600, fetchFn = fetch } = {}) {
  let nextRequestAt = 0;
  async function request(endpoint) {
    for (let attempt = 0; attempt < 2; attempt++) {
      await sleep(Math.max(0, nextRequestAt - Date.now()));
      try {
        const response = await fetchFn('https://music.163.com' + endpoint, {
          headers: { 'User-Agent': 'Mozilla/5.0', Referer: 'https://music.163.com/' },
          redirect: 'manual',
          signal: AbortSignal.timeout(18000)
        });
        if (ACCESS_CODES.has(response.status)) throw new AccessError('Public API access refused: HTTP ' + response.status);
        if (!response.ok) throw new Error('HTTP ' + response.status);
        const data = await response.json();
        if (ACCESS_CODES.has(data.code)) throw new AccessError('Public API access refused: code ' + data.code);
        if (data.code !== 200) {
          const error = new Error('API code ' + data.code);
          error.code = data.code;
          throw error;
        }
        return data;
      } catch (error) {
        if (error instanceof AccessError || error.code === -601 || attempt) throw error;
        await sleep(1500);
      } finally { nextRequestAt = Date.now() + delayMs; }
    }
  }
  return { request };
}

async function fetchArtistFans(artist, client) {
  const queries = artist.names.slice(0, 3);
  for (const query of queries) {
    try {
      const result = await client.request('/api/search/get?s=' + encodeURIComponent(query) + '&type=100&limit=50&offset=0');
      const count = exactFans(result, artist.id);
      if (count !== null) return { count, query };
    } catch (error) {
      if (error.code !== -601) throw error;
    }
  }
  // Resolve a renamed account by its known ID, never by a same-name guess.
  const detail = await client.request('/api/v1/artist/' + artist.id);
  if (String(detail.artist?.id) !== artist.id) throw new Error('Artist ID mismatch');
  const canonicalName = detail.artist.name;
  if (canonicalName && !queries.includes(canonicalName)) {
    const result = await client.request('/api/search/get?s=' + encodeURIComponent(canonicalName) + '&type=100&limit=50&offset=0');
    const count = exactFans(result, artist.id);
    if (count !== null) return { count, query: canonicalName };
  }
  throw new Error('No exact artist ID with a public fan count');
}

function writeCache(file, cache, counts, dates, stats) {
  const source = [
    '// Fan counts keyed by verified NetEase artist IDs; shared by index.html and local con.html.',
    '// Generated by sync-fans.js. Failed or unprocessed accounts retain their previous values.',
    'window.FANS_CACHE_UPDATED_AT = ' + JSON.stringify(new Date().toISOString()) + ';',
    'window.FANS_CACHE = ' + JSON.stringify(cache, null, 2) + ';',
    'window.FANS_CACHE_COUNTS = ' + JSON.stringify(counts, null, 2) + ';',
    'window.FANS_CACHE_FETCHED_AT = ' + JSON.stringify(dates, null, 2) + ';',
    '// Last sync: ' + stats.updated + ' updated, ' + stats.failed + ' failed, ' + stats.total + ' total. Access blocked: ' + stats.blocked + '.',
    ''
  ].join('\n');
  fs.writeFileSync(file, source, 'utf8');
}

async function syncFans({ dataFile = DATA_FILE, cacheFile = CACHE_FILE, artistIds, reportFile = process.env.FANS_SYNC_REPORT_FILE,
  client = createClient(), log = console.log, write = true, minimumCoverage = 0 } = {}) {
  const data = readWindow(dataFile).RapMapData;
  const allArtists = extractArtists(data);
  const artists = allArtists.filter(artist => !artistIds || artistIds.includes(artist.id));
  if (!artists.length) throw new Error('No artist IDs found in data/artist-data.js; cache was not changed.');
  const previous = fs.existsSync(cacheFile) ? readWindow(cacheFile) : {};
  const cache = { ...previous.FANS_CACHE }, counts = { ...previous.FANS_CACHE_COUNTS }, dates = { ...previous.FANS_CACHE_FETCHED_AT };
  const stats = { startedAt: new Date().toISOString(), total: artists.length, updated: 0, changed: 0, failed: 0, blocked: false, entries: [] };
  function report() {
    if (reportFile) fs.writeFileSync(reportFile, JSON.stringify(stats, null, 2), 'utf8');
  }
  log('Found ' + artists.length + ' unique singer IDs in the current project.');
  for (const artist of artists) {
    const row = { id: artist.id, name: artist.name, previous: cache[artist.id] ?? artist.fans };
    try {
      const result = await fetchArtistFans(artist, client);
      const display = formatFans(result.count);
      if (row.previous !== display) stats.changed++;
      cache[artist.id] = display;
      counts[artist.id] = result.count;
      dates[artist.id] = new Date().toISOString();
      Object.assign(row, { count: result.count, display, query: result.query, fetchedAt: dates[artist.id] });
      stats.updated++;
    } catch (error) {
      row.error = error.message;
      stats.failed++;
      if (error instanceof AccessError) stats.blocked = true;
    }
    stats.entries.push(row);
    if (stats.entries.length % 20 === 0 || row.error) {
      report();
      log(JSON.stringify({ done: stats.entries.length, total: stats.total, updated: stats.updated, failed: stats.failed,
        name: row.name, fans: row.display, error: row.error, blocked: stats.blocked }));
    }
    if (stats.blocked) break;
  }
  stats.finishedAt = new Date().toISOString();
  stats.publishable = !stats.blocked && stats.updated > 0 && stats.updated >= Math.ceil(stats.total * minimumCoverage);
  stats.written = false;
  if (write && stats.publishable) {
    if (!artistIds) {
      const activeIds = new Set(allArtists.map(artist => artist.id));
      for (const snapshot of [cache, counts, dates]) {
        for (const id of Object.keys(snapshot)) if (!activeIds.has(id)) delete snapshot[id];
      }
    }
    writeCache(cacheFile, cache, counts, dates, stats);
    stats.written = true;
  }
  report();
  log(JSON.stringify({ total: stats.total, updated: stats.updated, changed: stats.changed, failed: stats.failed,
    unprocessed: stats.total - stats.entries.length, blocked: stats.blocked, written: stats.written, cacheFile }));
  return stats;
}

if (require.main === module) {
  const mode = process.argv[2];
  const options = mode === '--probe' ? { artistIds: PROBE_IDS, write: false, minimumCoverage: 1 }
    : mode === '--publish' ? { minimumCoverage: PUBLISH_COVERAGE } : {};
  if (process.argv.length > 3 || (mode && !['--probe', '--publish'].includes(mode))) {
    console.error('Usage: node sync-fans.js [--probe | --publish]');
    process.exitCode = 1;
  } else syncFans(options).then(stats => {
    if (!stats.publishable || (mode !== '--publish' && stats.failed)) {
      console.error('Fan count check did not meet its requirements. ' + (stats.written ? 'Successful results were kept locally.' : 'Cache was not changed.'));
      process.exitCode = 1;
    }
  }).catch(error => { console.error(error.message); process.exitCode = 1; });
}

module.exports = { AccessError, formatFans, extractArtists, exactFans, createClient, fetchArtistFans, syncFans };
